#!/usr/bin/env bash
# ai-rules sync — composes AGENTS.md files into target projects from rule fragments.
#
# Usage:
#   ./sync.sh <project-dir>              sync one project
#   ./sync.sh --all                      sync every path in MANIFEST.txt
#   ./sync.sh --check <project-dir>      dry-run: report what would be written
#   ./sync.sh --stack a,b,c <dir>        force stack (skip detection)
#                                        tokens: fastify prisma supabase react vercel python
set -euo pipefail

AI_RULES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RULES_DIR="$AI_RULES_DIR/rules"
VERSION="$(cat "$AI_RULES_DIR/VERSION" | tr -d '[:space:]')"
MANIFEST="$AI_RULES_DIR/MANIFEST.txt"

CHECK_ONLY=0
FORCE_STACK=""
TARGETS=()

die() { echo "sync: error: $*" >&2; exit 1; }

# --- arg parsing -------------------------------------------------------------
while [ $# -gt 0 ]; do
  case "$1" in
    --check)  CHECK_ONLY=1; shift ;;
    --all)
      [ -f "$MANIFEST" ] || die "MANIFEST.txt not found (copy MANIFEST.example.txt and fill in your project paths)"
      while IFS= read -r line; do
        line="${line%%#*}"; line="$(echo "$line" | xargs)"
        [ -n "$line" ] && TARGETS+=("$line")
      done < "$MANIFEST"
      [ ${#TARGETS[@]} -gt 0 ] || die "MANIFEST.txt is empty"
      shift ;;
    --stack)  FORCE_STACK="$2"; shift 2 ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    -*)       die "unknown flag: $1" ;;
    *)        TARGETS+=("$1"); shift ;;
  esac
done
[ ${#TARGETS[@]} -gt 0 ] || die "no target. Usage: ./sync.sh [--check] [--all] [--stack a,b,c] <project-dir>"

# --- helpers -----------------------------------------------------------------

has_dep() {  # has_dep <dir> <dep-name> — greps package.json at root and one level deep
  local d="$1" dep="$2" pj
  for pj in "$d/package.json" "$d"/*/package.json "$d"/*/*/package.json; do
    [ -f "$pj" ] && [[ "$pj" != *node_modules* ]] && grep -q "\"$dep\"" "$pj" && return 0
  done
  return 1
}

detect_stack() {  # echoes space-separated stack tokens
  local d="$1" stack=""
  # Pure-Python project: no package.json but Python sources/requirements present.
  if [ ! -f "$d/package.json" ] && { [ -f "$d/requirements.txt" ] || compgen -G "$d/*.py" >/dev/null 2>&1; }; then
    echo "python"; return
  fi
  has_dep "$d" "fastify"                && stack="$stack fastify"
  { has_dep "$d" "@prisma/client" || [ -d "$d/prisma" ]; } && stack="$stack prisma"
  has_dep "$d" "@supabase/supabase-js"  && stack="$stack supabase"
  if has_dep "$d" "react" || has_dep "$d" "vite" || compgen -G "$d/vite.config.*" >/dev/null 2>&1; then
    stack="$stack react"
  fi
  [ -f "$d/vercel.json" ] && stack="$stack vercel"
  echo "${stack# }"
}

render() {  # render <fragment...> — concatenates fragments, expands placeholders
  local f
  for f in "$@"; do
    sed -e "s|{{AI_RULES_VERSION}}|$VERSION|g" -e "s|{{PROJECT_NAME}}|$PROJECT_NAME|g" "$RULES_DIR/$f"
    echo
  done
}

write_out() {  # write_out <path> — respects --check, backs up non-generated files
  local path="$1"
  if [ "$CHECK_ONLY" = 1 ]; then
    echo "  would write: $path"
    cat > /dev/null  # consume stdin
    return
  fi
  if [ -f "$path" ] && ! grep -q "GENERATED by ai-rules" "$path" 2>/dev/null; then
    cp "$path" "$path.bak"
    echo "  backed up existing: $path.bak"
  fi
  mkdir -p "$(dirname "$path")"
  cat > "$path"
  echo "  wrote: $path"
}

link_claude() {  # link_claude <dir> — CLAUDE.md -> AGENTS.md, stub fallback on Windows
  local d="$1" target="$1/CLAUDE.md"
  if [ "$CHECK_ONLY" = 1 ]; then
    [ -L "$target" ] && echo "  keep symlink: $target" || echo "  would link/stub: $target"
    return
  fi
  rm -f "$target"
  if ln -s AGENTS.md "$target" 2>/dev/null && [ -L "$target" ]; then
    echo "  symlinked: $target -> AGENTS.md"
  else
    cp "$RULES_DIR/stubs/CLAUDE.md" "$target"
    echo "  stubbed: $target (symlink unavailable — pointer file instead)"
  fi
}

sync_project() {
  local dir="${1%/}"
  [ -d "$dir" ] || { echo "!! skipping (not a directory): $dir"; return; }
  PROJECT_NAME="$(basename "$dir")"

  local stack
  stack="${FORCE_STACK:-$(detect_stack "$dir")}"
  [ -n "$stack" ] || { echo "!! $PROJECT_NAME: no stack detected, skipping (use --stack to force)"; return; }

  echo "== $PROJECT_NAME  [stack: $stack]"

  # Python projects get the standalone stub and nothing else.
  if [[ " $stack " == *" python "* ]]; then
    { echo "<!-- GENERATED by ai-rules v$VERSION -->"; echo; cat "$RULES_DIR/python-stub/AGENTS.md"; } \
      | write_out "$dir/AGENTS.md"
    link_claude "$dir"
    return
  fi

  local frags=(00-header.md 10-overview.md 20-code-style-js.md)
  [[ " $stack " == *" fastify "*  ]] && frags+=(30-backend-fastify.md)
  [[ " $stack " == *" prisma "*   ]] && frags+=(35-db-prisma.md)
  [[ " $stack " == *" supabase "* ]] && frags+=(36-db-supabase.md)
  [[ " $stack " == *" react "*    ]] && frags+=(40-frontend-react.md)
  frags+=(50-testing.md 60-git-hygiene.md 70-docs-policy.md 80-security-env.md)
  [[ " $stack " == *" vercel "*   ]] && frags+=(90-deploy-vercel.md)

  render "${frags[@]}" | write_out "$dir/AGENTS.md"
  link_claude "$dir"

  # Scoped AGENTS.md for backend/api/ and frontend/ subdirectories.
  local scopedir
  for scopedir in backend api; do
    if [ -d "$dir/$scopedir" ] && [[ " $stack " == *" fastify "* ]]; then
      local bfrags=(00-header.md 30-backend-fastify.md)
      [[ " $stack " == *" prisma "*   ]] && bfrags+=(35-db-prisma.md)
      [[ " $stack " == *" supabase "* ]] && bfrags+=(36-db-supabase.md)
      render "${bfrags[@]}" | write_out "$dir/$scopedir/AGENTS.md"
      link_claude "$dir/$scopedir"
    fi
  done
  if [ -d "$dir/frontend" ] && [[ " $stack " == *" react "* ]]; then
    render 00-header.md 40-frontend-react.md | write_out "$dir/frontend/AGENTS.md"
    link_claude "$dir/frontend"
  fi

  # Warnings for known footguns.
  if [ -f "$dir/package-lock.json" ] && { [ -f "$dir/pnpm-lock.yaml" ] || [ -f "$dir/yarn.lock" ]; }; then
    echo "  ⚠ mixed lockfiles detected (package-lock.json + pnpm/yarn) — consolidate on npm"
  fi
}

for t in "${TARGETS[@]}"; do sync_project "$t"; done
[ "$CHECK_ONLY" = 1 ] && echo "(check mode — nothing was written)"
echo "done. ai-rules v$VERSION"
